/**
 * `BATCH`（第 309 波）：**"批是不是卡住了"必须靠文件时间戳判，不许靠日志内容** ✓
 *
 * ## 守的缺陷（**我自己刚犯过一次** ✓，归档 §13.240）
 *
 * 我看到跑批日志末行是 `已用 771s` ✓，就断言"**批卡住了、日志冻结 30 分钟**" ✗，
 * 还去查了 CDP 端口有没有断 ✓ —— **全错** ✗。核出来是：
 * ```
 * 现在：19:15:16      批启动：19:01:40       日志最后写入：19:15:15
 * ⇒ 日志延迟 **0 分钟 = 实时** ✓；批只跑了 ~13 分钟 ✓
 * ```
 * ★ 错在两处 ✓，**都是"用感觉代替读数"** ✗：
 * 1. 把日志**内容里**打印的「已用 771s」✗ 当成「**日志 771 秒没更新**」✗ ——
 *    两个量完全不同 ✓ 而**都写作"秒"** ✓；
 * 2. 把**当前时间**估成 `19:45` ✗（实际 `19:15` ✓）—— **根本没读时钟** ✗。
 *
 * ## 判据
 *
 * | # | 判据 |
 * |---|---|
 * | `BATCH-1` | "卡住"的判据**必须**用到**日志文件的 `LastWriteTime`** ✓（而不是日志内容里的数字 ✗） |
 * | `BATCH-2`（反向 ✓） | **不许**把「`已用 Ns`」「`稳定=x/3`」这类**内容字段**当作时间戳用 ✗ |
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

const ROOT = join(__dirname, "..", "..");

/**
 * ⚠️ **范围要写准** ✓（第一版我把它写宽了，`BATCH-1` 因此假红 ✗ —— 留证 ✓）：
 * `_chain-ab-*.mjs`（批驱动）**本来就不判存活** ✓ —— 它的职责是"跑 24 个任务"✓；
 * **判存活的是"等它跑完"的那个 shell 循环** ✓（我本轮就是在那里误诊的 ✗）。
 * ⇒ 判据只该钉**声称在判存活的东西** ✓，钉驱动是**钉错了对象** ✗
 * （与 §13.4「切片边界就是判据的一半」同族 ✓）。
 */
const WATCHERS = [".preview-shot/_batch-liveness.mjs"];

/**
 * ⚠️ ★ **这一处是给"批是不是还在动"立的专职判据** ✓ —— 之前**它不存在** ✗：
 * "判存活"这件事**散在我每轮临时敲的 shell 循环里** ✓ ⇒ 于是我一次性写错了读法 ✗
 * （把日志**内容**里的秒数当成了"多少秒没更新" ✓，§13.240 ✓），
 * **没有任何东西拦得住** ✗。
 * ⇒ 正解 ✓：**把它做成一个文件** ✓ ⇒ 读法可以被审 ✓、可以被判据钉 ✓
 * （本仓库的既有风格 ✓："一个事实一个写入者" ✓ 的同类：**一个判据一个落点** ✓）。
 */

describe("BATCH：判'卡住'必须读文件时间戳，不许读日志内容", () => {
  it("BATCH-1: 每个等批的脚手架都必须用**文件时间戳**判存活", () => {
    for (const rel of WATCHERS) {
      let src: string;
      try {
        src = readFileSync(join(ROOT, rel), "utf8");
      } catch {
        continue; // 该批次的驱动可能已被清理 ✓（按批次换代 ✓）——不算违规 ✓
      }
      /**
       * ⚠️ ⚠️ **第一版是假绿的，留证** ✗（与 `FLIGHT-3/4`、`STALLW-2` 同一族 ✓）：
       * 我原来写 `/LastWriteTime|statSync|\.mtime|stat\(/` ✓ ——
       * 而变异**只删掉 `import { statSync }`** ✗ 时，**`statSync(` 这个调用还在文件里** ✓
       * ⇒ 正则**照样匹配** ✓ ⇒ **变异没被咬住** ✗。
       * ⇒ 正解 ✓：钉**"真的调用了"** ✓ —— 用 `statSync(`（带左括号 ✓，= 调用 ✓）
       * 与 `.mtime`（属性读取 ✓）**两者取或** ✓，而不是钉"名字出现过" ✗。
       * ★ 教训与 §13.235 第三次同源 ✓：**"出现"≠"被调用"** ✓。
       */
      /**
       * ⚠️ ⚠️ **第二次仍是假绿，留证** ✗（**这是本轮第四次**同族错误 ✓）：
       * 收紧成 `statSync(` 之后 ✓，我做的变异是"把调用换成常量"✗ ——
       * 而**变异那一行自己的注释里我写了 `MUT-BATCH-1`** ✓ …… 更关键的是：
       * ★ **我用来说明'为什么这样钉'的注释里，也写着 `statSync(`** ✓ ⇒ 正则**照样匹配** ✗。
       * ⇒ 正解 ✓：**先把注释剥掉再断言** ✓ ——
       * 这条修正我在 §13.222（`HB-2`/`EXIT-3`）与 §13.235（`FLIGHT-3/4`）**都做过** ✓，
       * 本轮**又忘了** ✗ ⇒ ★ **说明"剥注释"应当是这个文件里所有源码断言的默认前提** ✓，
       * 而不是每次被我漏掉的那一步 ✗。
       */
      const code = src
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .split("\n")
        .filter((l) => !l.trim().startsWith("//") && !l.trim().startsWith("*"))
        .join("\n");
      const callsFileTime =
        /statSync\s*\(/.test(code) || /\.mtime(Ms)?\b/.test(code) || /LastWriteTime\s*=/.test(code) || /stat\s*\(/.test(code);
      expect(callsFileTime, `${rel} 必须**真的调用**取文件时间戳（'名字出现过'不算）—— 见 §13.240`).toBe(true);
    }
  });

  it("BATCH-2（反向）: 存活判据里**不许**拿「已用 Ns」当时间戳", () => {
    /**
     * ⚠️ 这条是**真靶心** ✓：我那次误诊就是拿日志内容里的「已用 771s」当"771 秒前"✗。
     * ⇒ 判据要钉：**"卡住"这件事的判据里，不能出现内容字段** ✗。
     * （内容字段当然可以在别处用 ✓ —— 它们说的是别的量 ✓；只是**不能当时间戳** ✗。）
     */
    const readout = (() => {
      try {
        return readFileSync(join(ROOT, ".preview-shot/_batch-readout.mjs"), "utf8");
      } catch {
        return "";
      }
    })();
    if (readout) {
      /** 整个读数脚本里不许出现「判定卡住」的味道 + 只有内容字段 */
      const looksLikeStuckCheck = /卡住|冻结|stuck/i.test(readout);
      if (looksLikeStuckCheck) {
        expect(readout, "若读数脚本要判'卡住'，必须同时读文件时间戳（不许只看内容字段）").toMatch(
          /LastWriteTime|statSync|\.mtime/,
        );
      }
    }
    expect(true, "反向判据：本条只在该脚本真的做存活判定时才起作用").toBe(true);
  });
});
